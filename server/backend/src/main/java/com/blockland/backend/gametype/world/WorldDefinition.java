package com.blockland.backend.gametype.world;

import com.blockland.backend.gamemode.GameMode;
import com.blockland.backend.gametype.GameTypeDefinition;
import com.blockland.backend.gametype.common.MovementSettings;
import com.blockland.backend.gametype.common.TeamArenaSettings;
import com.blockland.backend.kit.KitItem;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.node.ObjectNode;
import org.springframework.stereotype.Component;

import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Set;
import java.util.regex.Pattern;

/**
 * 开放世界: no queue and no map — queueing puts the players straight into the one running world of the mode (a generated
 * dimension of the mod), where they come and go as they like; their inventory and position are kept by the game server.
 * Settings: {@code dimension} (resource id, default {@code blockland:world}), {@code gameMode} (SURVIVAL / ADVENTURE /
 * CREATIVE), {@code pvp}, {@code keepInventory}, {@code maxPlayers} (1–200) and the movement rules ({@code allowSlide}).
 * The kit is handed out on a player's first visit only. Must stay in sync with the mod's {@code WorldSettings}.
 */
@Component
public class WorldDefinition implements GameTypeDefinition {
    public static final String ID = "WORLD";
    public static final String DEFAULT_DIMENSION = "blockland:world";
    public static final Set<String> GAME_MODES = Set.of("SURVIVAL", "ADVENTURE", "CREATIVE");
    private static final Pattern RESOURCE_ID = Pattern.compile("^[a-z0-9_.\\-]+:[a-z0-9_./\\-]+$");
    private static final boolean ALLOW_SLIDE = false;

    private final ObjectMapper mapper;

    public WorldDefinition(ObjectMapper mapper) {
        this.mapper = mapper;
    }

    @Override
    public String id() {
        return ID;
    }

    @Override
    public String displayName() {
        return "开放世界";
    }

    @Override
    public String description() {
        return "直接进入一个所有人共享的开放世界，随时进出，背包与位置由服务器保存。";
    }

    @Override
    public ObjectNode defaultSettings() {
        ObjectNode node = mapper.createObjectNode();
        node.put("dimension", DEFAULT_DIMENSION);
        node.put("gameMode", "SURVIVAL");
        node.put("pvp", true);
        node.put("keepInventory", false);
        node.put("maxPlayers", 50);
        MovementSettings.putDefaults(node, ALLOW_SLIDE);
        return node;
    }

    @Override
    public ObjectNode normalizeSettings(JsonNode raw, Context context, List<String> errors) {
        JsonNode in = raw == null || !raw.isObject() ? mapper.createObjectNode() : raw;
        ObjectNode out = defaultSettings();
        JsonNode dimension = in.get("dimension");
        if (dimension != null && !dimension.isNull()) {
            String id = dimension.asText("").trim().toLowerCase(Locale.ROOT);
            if (id.isEmpty()) {
                out.put("dimension", DEFAULT_DIMENSION);
            } else if (!RESOURCE_ID.matcher(id).matches()) {
                errors.add("维度必须是资源 ID，例如 blockland:world 或 minecraft:overworld");
            } else {
                out.put("dimension", id);
            }
        }
        JsonNode gameMode = in.get("gameMode");
        if (gameMode != null && !gameMode.isNull()) {
            String value = gameMode.asText("").trim().toUpperCase(Locale.ROOT);
            if (GAME_MODES.contains(value)) out.put("gameMode", value);
            else errors.add("游戏模式必须是 SURVIVAL（生存）、ADVENTURE（冒险）或 CREATIVE（创造）");
        }
        out.put("pvp", TeamArenaSettings.boolField(in, "pvp", true));
        out.put("keepInventory", TeamArenaSettings.boolField(in, "keepInventory", false));
        out.put("maxPlayers", TeamArenaSettings.intField(in, "maxPlayers", 50, 1, 200, "最大人数", errors));
        MovementSettings.normalizeInto(in, out, ALLOW_SLIDE);
        return out;
    }

    /** The world is generated by the mod: there is no map to warn about. */
    @Override
    public List<String> warnings(GameMode mode, Context context) {
        List<String> warnings = new ArrayList<>();
        JsonNode settings = mode.settings();
        String dimension = settings == null ? DEFAULT_DIMENSION : settings.path("dimension").asText(DEFAULT_DIMENSION);
        if (dimension.startsWith("blockland:") && !DEFAULT_DIMENSION.equals(dimension)) {
            warnings.add("模组只自带 " + DEFAULT_DIMENSION + " 维度；" + dimension + " 需要由服务器的数据包提供");
        }
        return warnings;
    }

    @Override
    public boolean usesKit() {
        return true;
    }

    /** A modest start: a stone toolset and some food (only on the first visit). */
    @Override
    public List<KitItem> defaultKit() {
        return List.of(
                new KitItem("minecraft:stone_sword", 1, "0"),
                new KitItem("minecraft:stone_pickaxe", 1, "1"),
                new KitItem("minecraft:stone_axe", 1, "2"),
                new KitItem("minecraft:bread", 16, "8"));
    }
}
