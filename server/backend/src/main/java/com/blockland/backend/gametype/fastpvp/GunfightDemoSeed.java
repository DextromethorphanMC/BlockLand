package com.blockland.backend.gametype.fastpvp;

import com.blockland.backend.gamemode.GameModeService;
import com.blockland.backend.kit.KitItem;
import com.blockland.backend.map.MapService;
import com.blockland.backend.modegroup.ModeGroup;
import com.blockland.backend.modegroup.ModeGroupService;
import com.blockland.backend.seed.CoverArt;
import com.blockland.backend.seed.DemoSeed;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.node.ArrayNode;
import com.fasterxml.jackson.databind.node.ObjectNode;
import org.springframework.core.annotation.Order;
import org.springframework.stereotype.Component;

import java.util.ArrayList;
import java.util.List;

/**
 * 枪战1v1: a limited-time ("限时开放") pistol and knife duel in the "PVP 竞技" group, with a generated cover.
 * The P9 and knife items come with a newer mod version, so the kit may name items the connected server has not
 * reported yet; the mode is created anyway and shows a warning until the server knows them.
 */
@Component
@Order(50)
public class GunfightDemoSeed implements DemoSeed {
    private static final String MODE_ID = "gunfight_1v1";
    private static final String GROUP_ID = "pvp";
    /** Generated by {@link FastPvpDemoSeed}. */
    private static final String DEMO_MAP = "demo_arena";
    /** 2026-11-30 23:59:59 China time. */
    private static final String AVAILABLE_UNTIL = "2026-11-30T15:59:59Z";

    private final GameModeService modes;
    private final ModeGroupService groups;
    private final MapService maps;
    private final ObjectMapper mapper;

    public GunfightDemoSeed(GameModeService modes, ModeGroupService groups, MapService maps, ObjectMapper mapper) {
        this.modes = modes;
        this.groups = groups;
        this.maps = maps;
        this.mapper = mapper;
    }

    @Override
    public String id() {
        return "fastpvp-gunfight";
    }

    @Override
    public void apply() {
        if (!modes.exists(MODE_ID)) {
            ObjectNode settings = mapper.createObjectNode();
            settings.put("teamSize", 1);
            settings.put("teamCount", 2);
            // an empty pool means every FastPVP map, in case an admin removed the demo arena
            ArrayNode mapIds = settings.putArray("mapIds");
            if (maps.exists(DEMO_MAP) && FastPvpDefinition.ID.equalsIgnoreCase(maps.get(DEMO_MAP).gameType())) mapIds.add(DEMO_MAP);
            settings.put("countdownSeconds", 5);
            settings.put("endingSeconds", 5);
            settings.put("allowBlockBreak", false);
            settings.put("allowBlockPlace", false);
            List<KitItem> kit = List.of(
                    new KitItem("blockland:p9", 1, "0"),
                    new KitItem("blockland:pistol_ammo", 60, "1"),
                    new KitItem("blockland:butterfly", 1, "2"));
            modes.createAllowingUnknownItems(new GameModeService.Request(MODE_ID, "枪战1v1", FastPvpDefinition.ID,
                    "手枪对决：一把 P9 手枪、60 发手枪弹药与一把蝴蝶刀，爆头和背刺伤害更高。", true, 300, AVAILABLE_UNTIL, settings, kit));
        }
        if (modes.get(MODE_ID).coverVersion() == null) modes.setCover(MODE_ID, CoverArt.pistol(5));

        if (groups.exists(GROUP_ID)) {
            ModeGroup pvp = groups.get(GROUP_ID);
            List<String> modeIds = new ArrayList<>(pvp.modeIds().stream().filter(modes::exists).toList());
            if (!modeIds.contains(MODE_ID)) {
                modeIds.add(MODE_ID);
                groups.update(GROUP_ID, pvp.withModeIds(modeIds));
            }
        }
    }
}
