package com.blockland.server.farterrain;

import com.blockland.BlockLand;
import com.blockland.mixin.farterrain.ServerChunkCacheAccess;
import it.unimi.dsi.fastutil.longs.Long2ObjectOpenHashMap;
import it.unimi.dsi.fastutil.longs.LongOpenHashSet;
import net.minecraft.server.MinecraftServer;
import net.minecraft.server.level.ServerChunkCache;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.server.level.ServerPlayer;
import net.minecraft.world.level.chunk.ChunkAccess;
import net.minecraft.world.level.chunk.status.ChunkStatus;
import net.minecraft.world.level.levelgen.NoiseBasedChunkGenerator;
import net.minecraft.server.level.ChunkResult;

import java.util.HashMap;
import java.util.Iterator;
import java.util.Map;
import java.util.UUID;
import java.util.concurrent.CompletableFuture;
import java.util.concurrent.ConcurrentLinkedQueue;
import java.util.concurrent.atomic.AtomicBoolean;
import java.util.function.Function;
import java.util.function.ToIntFunction;

/**
 * Real chunks generated in the background round the players (rendering spec §22, as Distant Horizons does): every chunk
 * of a noise-generated level within {@code generateRadius} of a player that does not exist yet is generated by the game's
 * own world generation — terrain, surface, caves, trees and all — nearest first, a few at a time, paused while the server
 * is behind. A finished chunk loads like any other (its columns are captured), unloads once nothing holds it and is saved,
 * so the far terrain round the players is the real terrain and an estimate only lies beyond. Which chunks are missing is
 * worked out on a worker (the region files' tables); the generation is asked for on the server thread.
 */
final class Generation {
    /** Server tick time above which no new chunk is started (milliseconds). */
    private static final double BUSY_MS = 40;
    /** Chunk positions looked at per scan of one player's spiral (a radius of 4096 chunks is about 53 million). */
    private static final int SCAN = 16384;
    /** A player whose spiral centre is this many chunks away starts a new spiral round where they are. */
    private static final int RECENTRE = 4;

    private final MinecraftServer server;
    private final Workers workers;
    private final Map<UUID, Spiral> spirals = new HashMap<>();
    /** Chunks being generated (per level and chunk key), kept alive by a fresh ticket every tick. */
    private final Map<ServerLevel, Long2ObjectOpenHashMap<CompletableFuture<ChunkResult<ChunkAccess>>>> inFlight = new HashMap<>();
    private long started, finished;

    /** One player's search outwards, ring by ring, for chunks that do not exist yet (filled on a worker). */
    private static final class Spiral {
        ServerLevel level;
        int cx, cz, ring, along, radius;
        boolean done;
        final ConcurrentLinkedQueue<Long> missing = new ConcurrentLinkedQueue<>();
        final AtomicBoolean scanning = new AtomicBoolean();
    }

    Generation(MinecraftServer server, Workers workers) {
        this.server = server;
        this.workers = workers;
    }

    /** Server thread, every tick. */
    void tick(FarTerrainSettings settings, Function<ServerLevel, DimensionTerrain> dimensions, ToIntFunction<ServerPlayer> reach) {
        keepAlive();
        int base = settings.generateRadius() >> 4;
        if (base <= 0) {
            spirals.clear();
            return;
        }
        boolean busy = server.getAverageTickTimeNanos() / 1e6 > BUSY_MS;
        java.util.Set<UUID> present = new java.util.HashSet<>();
        for (ServerPlayer player : server.getPlayerList().getPlayers()) {
            ServerLevel level = (ServerLevel) player.level();
            if (!(level.getChunkSource().getGenerator() instanceof NoiseBasedChunkGenerator)) continue;
            present.add(player.getUUID());
            int pcx = player.getBlockX() >> 4, pcz = player.getBlockZ() >> 4;
            // at least as far as the real far chunks this player asks for (spec §23), never beyond what they may ask
            int radius = Math.max(base, Math.min(reach.applyAsInt(player) >> 4, settings.columnDistance()));
            Spiral s = spirals.get(player.getUUID());
            if (s == null || s.level != level || Math.max(Math.abs(s.cx - pcx), Math.abs(s.cz - pcz)) > RECENTRE) {
                s = new Spiral();
                s.level = level;
                s.cx = pcx;
                s.cz = pcz;
                spirals.put(player.getUUID(), s);
            }
            if (radius > s.radius) {
                // asked farther than the spiral went: it carries on outwards
                s.radius = radius;
                s.done = false;
            }
            if (!s.done && s.missing.size() < settings.generateConcurrency() * 4 && s.scanning.compareAndSet(false, true)) {
                Spiral spiral = s;
                DimensionTerrain dim = dimensions.apply(level);
                workers.run(Workers.IMPORT, 0, () -> {
                    try {
                        scan(spiral, dim, spiral.radius);
                    } finally {
                        spiral.scanning.set(false);
                    }
                });
            }
            if (busy) continue;
            Long2ObjectOpenHashMap<CompletableFuture<ChunkResult<ChunkAccess>>> running = inFlight.computeIfAbsent(level, k -> new Long2ObjectOpenHashMap<>());
            ServerChunkCache chunks = level.getChunkSource();
            Long key;
            while (running.size() < settings.generateConcurrency() && (key = s.missing.poll()) != null) {
                int x = Chunks.x(key), z = Chunks.z(key);
                if (running.containsKey((long) key) || chunks.hasChunk(x, z)) continue;
                // not getChunkFuture: on the server thread it waits for the chunk (the tick would stand still until it is made)
                running.put((long) key, ((ServerChunkCacheAccess) chunks).blockland$scheduleChunk(x, z, ChunkStatus.FULL, true));
                started++;
            }
        }
        spirals.keySet().retainAll(present);
    }

    /** The chunks being generated get a fresh one-tick ticket each tick (so they never unload half made); finished ones go. */
    private void keepAlive() {
        for (Map.Entry<ServerLevel, Long2ObjectOpenHashMap<CompletableFuture<ChunkResult<ChunkAccess>>>> e : inFlight.entrySet()) {
            ServerChunkCache chunks = e.getKey().getChunkSource();
            for (Iterator<Long2ObjectOpenHashMap.Entry<CompletableFuture<ChunkResult<ChunkAccess>>>> it = e.getValue().long2ObjectEntrySet().iterator(); it.hasNext(); ) {
                Long2ObjectOpenHashMap.Entry<CompletableFuture<ChunkResult<ChunkAccess>>> entry = it.next();
                if (entry.getValue().isDone()) {
                    it.remove();
                    finished++;
                    continue;
                }
                try {
                    ((ServerChunkCacheAccess) chunks).blockland$scheduleChunk(Chunks.x(entry.getLongKey()), Chunks.z(entry.getLongKey()),
                            ChunkStatus.FULL, true);
                } catch (RuntimeException ex) {
                    BlockLand.LOGGER.debug("[BlockLand] Far terrain generation could not keep a chunk", ex);
                    it.remove();
                }
            }
        }
    }

    /** Worker: walks the spiral until it found enough missing chunks or looked at {@link #SCAN} positions. */
    private static void scan(Spiral s, DimensionTerrain dim, int radius) {
        LongOpenHashSet queued = new LongOpenHashSet();
        for (Long k : s.missing) queued.add((long) k);
        int want = 64;
        for (int n = 0; n < SCAN && !s.done && s.missing.size() < want; n++) {
            int dx, dz;
            int r = s.ring;
            if (r == 0) {
                dx = dz = 0;
                s.ring = 1;
                s.along = 0;
            } else {
                // the ring of Chebyshev radius r: 8r positions, walked side by side
                int side = s.along / (2 * r), offset = s.along % (2 * r);
                switch (side) {
                    case 0 -> { dx = -r + offset; dz = -r; }
                    case 1 -> { dx = r; dz = -r + offset; }
                    case 2 -> { dx = r - offset; dz = r; }
                    default -> { dx = -r; dz = r - offset; }
                }
                if (++s.along >= 8 * r) {
                    s.along = 0;
                    if (++s.ring > radius) s.done = true;
                }
            }
            if ((long) dx * dx + (long) dz * dz > (long) radius * radius) continue;
            int x = s.cx + dx, z = s.cz + dz;
            if (dim.regionHas(x, z)) continue;
            long key = Chunks.key(x, z);
            if (queued.add(key)) s.missing.add(key);
        }
    }

    /** Status line: chunks generating now, started and finished since the server started. */
    String status() {
        int running = 0;
        for (Long2ObjectOpenHashMap<?> m : inFlight.values()) running += m.size();
        return String.format("generation: %d running, %d started, %d finished, %d players searching", running, started, finished,
                spirals.size());
    }

    void stop() {
        inFlight.clear();
        spirals.clear();
    }
}
